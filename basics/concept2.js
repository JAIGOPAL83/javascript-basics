// Arrow Function
// Arrow functions provide a concise syntax for writing functions in JavaScript. They are often used for shorter functions and can help improve readability.

const add = (a, b) => {
  return a + b;
};

console.log("add = " + add(2, 3)); // Output: 5

const multiply = (a, b) => a * b;

console.log("multiply = " + multiply(4, 5)); // Output: 20
